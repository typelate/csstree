// Package nodegen writes the boilerplate of the AST node types of package
// csstree from their struct definitions: their Type, Location and
// MarshalJSON methods, their Walk, Clone and FromPlainObject functions, and
// nodeConfigs, which returns the NodeConfig of every node type.
//
// A node type is a struct in a node_*.go file whose doc comment holds the
// directive
//
//	//csstree:node [name=<type>] [walkContext=<context>]
//
// where name is the upstream node type (default: the Go type name) and
// walkContext is upstream's walkContext. Its first field is Loc *Location
// and every other field has a css tag giving its upstream name and its
// structure, the field types of upstream's structure written with
// lowercase string, boolean and null, node type names, and [A|B] for a
// list of A or B nodes ([] for a list of any nodes):
//
//	Name    string       `css:"name,string"`
//	Matcher string       `css:"matcher,string|null"`
//	Prelude Node         `css:"prelude,SelectorList|Raw"`
//	Block   *Block       `css:"block,Block|null"`
//	Items   *List[Node]  `css:"children,[Atrule|Rule]"`
//
// The Go type decides the code: a string field is encoded as a string, or
// as null when empty if its structure allows null; a Node, *T or
// *List[Node] field is walked, cloned and read as a node, a node of type T
// or a list. A string field whose upstream value is not a string or null
// names the functions that convert it instead:
//
//	Important string `css:"important,boolean|string,json=importantJSON,read=plainObjectImportant"`
//
// where importantJSON(string) any returns the JSON value and
// plainObjectImportant(*PlainObjectReader, map[string]any, string) string
// reads the field from a plain object.
//
// Each node type supplies generate<GoName>, its GenerateFunc.
package nodegen

import (
	"bytes"
	"cmp"
	"fmt"
	"go/ast"
	"go/format"
	"go/parser"
	"go/token"
	"path/filepath"
	"slices"
	"strconv"
	"strings"
)

// header starts the generated file.
const header = "// Code generated by nodegen; DO NOT EDIT.\n"

const directive = "//csstree:node"

// Generate returns the generated Go source for the node types of the
// node_*.go files in dir.
func Generate(dir string) ([]byte, error) {
	paths, err := filepath.Glob(filepath.Join(dir, "node_*.go"))
	if err != nil {
		return nil, err
	}

	fset := token.NewFileSet()
	var files []*ast.File
	for _, path := range paths {
		if strings.HasSuffix(path, "_test.go") {
			continue
		}
		file, err := parser.ParseFile(fset, path, nil, parser.ParseComments|parser.SkipObjectResolution)
		if err != nil {
			return nil, err
		}
		files = append(files, file)
	}

	return generate(fset, files)
}

// nodeType is a node struct and its directive.
type nodeType struct {
	goName      string
	name        string
	walkContext string
	spec        *ast.StructType
	fields      []field
}

// fieldKind is what the Go type of a field makes of it.
type fieldKind int

const (
	stringKind    fieldKind = iota // string
	nodeKind                       // Node
	typedNodeKind                  // *T for a node type T
	listKind                       // *List[Node]
)

// field is a node field after its css tag.
type field struct {
	goName string
	name   string
	kind   fieldKind
	// goType is the struct name of a typedNodeKind field.
	goType string
	types  []fieldType
	json   string
	read   string
}

func (f field) walked() bool {
	return f.kind != stringKind
}

func (f field) nullable() bool {
	return slices.ContainsFunc(f.types, func(t fieldType) bool { return t.kind == "null" })
}

// fieldType is one alternative of a field's structure: kind is "string",
// "boolean", "null", "node" (of type node) or "list" (of types list).
type fieldType struct {
	kind string
	node string
	list []string
}

func generate(fset *token.FileSet, files []*ast.File) ([]byte, error) {
	types, err := findNodeTypes(fset, files)
	if err != nil {
		return nil, err
	}

	names := make(map[string]string, len(types))
	for _, t := range types {
		names[t.goName] = t.name
	}
	for i := range types {
		fields, err := readFields(fset, types[i].goName, types[i].spec, names)
		if err != nil {
			return nil, err
		}
		types[i].fields = fields
	}

	var buf bytes.Buffer
	buf.WriteString(header)
	buf.WriteString("\npackage csstree\n")
	buf.WriteString("\n// nodeConfigs returns the NodeConfig of every node type by name.\n")
	buf.WriteString("func nodeConfigs() map[string]NodeConfig {\nreturn map[string]NodeConfig{\n")
	for _, t := range types {
		writeConfig(&buf, t)
	}
	buf.WriteString("}\n}\n")
	for _, t := range types {
		writeNodeType(&buf, t)
	}

	result, err := format.Source(buf.Bytes())
	if err != nil {
		return nil, fmt.Errorf("formatting generated code: %w", err)
	}
	return result, nil
}

// findNodeTypes returns the structs with the node directive, by node type
// name.
func findNodeTypes(fset *token.FileSet, files []*ast.File) ([]nodeType, error) {
	var result []nodeType
	for _, file := range files {
		for _, decl := range file.Decls {
			decl, ok := decl.(*ast.GenDecl)
			if !ok || decl.Tok != token.TYPE {
				continue
			}
			for _, spec := range decl.Specs {
				spec := spec.(*ast.TypeSpec)
				doc := spec.Doc
				if doc == nil && len(decl.Specs) == 1 {
					doc = decl.Doc
				}
				args, ok := findDirective(doc)
				if !ok {
					continue
				}
				structType, ok := spec.Type.(*ast.StructType)
				if !ok {
					return nil, fmt.Errorf("%s: %s: node type is not a struct", fset.Position(spec.Pos()), spec.Name.Name)
				}
				t := nodeType{goName: spec.Name.Name, name: spec.Name.Name, spec: structType}
				for _, arg := range args {
					key, value, _ := strings.Cut(arg, "=")
					switch {
					case key == "name" && value != "":
						t.name = value
					case key == "walkContext" && value != "":
						t.walkContext = value
					default:
						return nil, fmt.Errorf("%s: %s: unknown directive argument %q", fset.Position(spec.Pos()), spec.Name.Name, arg)
					}
				}
				result = append(result, t)
			}
		}
	}

	slices.SortFunc(result, func(a, b nodeType) int { return cmp.Compare(a.name, b.name) })
	for i := 1; i < len(result); i++ {
		if result[i].name == result[i-1].name {
			return nil, fmt.Errorf("node type %s is declared by %s and %s", result[i].name, result[i-1].goName, result[i].goName)
		}
	}
	return result, nil
}

// findDirective returns the arguments of the node directive in doc.
func findDirective(doc *ast.CommentGroup) ([]string, bool) {
	if doc == nil {
		return nil, false
	}
	for _, comment := range doc.List {
		rest, ok := strings.CutPrefix(comment.Text, directive)
		if ok && (rest == "" || rest[0] == ' ') {
			return strings.Fields(rest), true
		}
	}
	return nil, false
}

// readFields reads the fields of a node struct; names maps the Go names of
// node structs to their node types.
func readFields(fset *token.FileSet, goName string, spec *ast.StructType, names map[string]string) ([]field, error) {
	fail := func(pos token.Pos, msg string, args ...any) error {
		return fmt.Errorf("%s: %s: %s", fset.Position(pos), goName, fmt.Sprintf(msg, args...))
	}

	list := spec.Fields.List
	if len(list) == 0 || len(list[0].Names) != 1 || list[0].Names[0].Name != "Loc" || typeSource(list[0].Type) != "*Location" || list[0].Tag != nil {
		return nil, fail(spec.Pos(), "the first field must be Loc *Location without a tag")
	}

	var result []field
	for _, astField := range list[1:] {
		if len(astField.Names) != 1 {
			return nil, fail(astField.Pos(), "declare one field per line")
		}
		f := field{goName: astField.Names[0].Name}
		if astField.Tag == nil {
			return nil, fail(astField.Pos(), "field %s has no css tag", f.goName)
		}
		tag, err := cssTag(astField.Tag.Value)
		if err != nil {
			return nil, fail(astField.Pos(), "field %s: %v", f.goName, err)
		}
		if err := f.parseTag(tag); err != nil {
			return nil, fail(astField.Pos(), "field %s: %v", f.goName, err)
		}
		if err := f.setKind(typeSource(astField.Type), names); err != nil {
			return nil, fail(astField.Pos(), "field %s: %v", f.goName, err)
		}
		result = append(result, f)
	}
	return result, nil
}

// typeSource returns the source of a field type, "" for a type nodegen does
// not handle.
func typeSource(expr ast.Expr) string {
	switch expr := expr.(type) {
	case *ast.Ident:
		return expr.Name
	case *ast.StarExpr:
		if inner := typeSource(expr.X); inner != "" {
			return "*" + inner
		}
	case *ast.IndexExpr:
		if inner, index := typeSource(expr.X), typeSource(expr.Index); inner != "" && index != "" {
			return inner + "[" + index + "]"
		}
	}
	return ""
}

// cssTag returns the value of the css key of a struct tag literal, which
// must be the only key.
func cssTag(literal string) (string, error) {
	tag, err := strconv.Unquote(literal)
	if err != nil {
		return "", err
	}
	quoted, ok := strings.CutPrefix(tag, "css:")
	if !ok {
		return "", fmt.Errorf("tag %s is not a css tag", literal)
	}
	value, err := strconv.Unquote(quoted)
	if err != nil {
		return "", fmt.Errorf("tag %s is not a css tag: %v", literal, err)
	}
	return value, nil
}

// parseTag reads name,types[,json=f][,read=f].
func (f *field) parseTag(tag string) error {
	parts := strings.Split(tag, ",")
	if len(parts) < 2 || parts[0] == "" {
		return fmt.Errorf("css tag %q does not start with a name and the field types", tag)
	}
	f.name = parts[0]

	types, err := parseFieldTypes(parts[1])
	if err != nil {
		return fmt.Errorf("css tag %q: %v", tag, err)
	}
	f.types = types

	for _, option := range parts[2:] {
		key, value, _ := strings.Cut(option, "=")
		switch {
		case key == "json" && token.IsIdentifier(value):
			f.json = value
		case key == "read" && token.IsIdentifier(value):
			f.read = value
		default:
			return fmt.Errorf("css tag %q: unknown option %q", tag, option)
		}
	}
	return nil
}

// parseFieldTypes reads alternatives separated by |, where a list is
// [A|B].
func parseFieldTypes(s string) ([]fieldType, error) {
	var result []fieldType
	for s != "" {
		var alternative string
		if strings.HasPrefix(s, "[") {
			end := strings.IndexByte(s, ']')
			if end < 0 {
				return nil, fmt.Errorf("unterminated list in %q", s)
			}
			alternative, s = s[:end+1], s[end+1:]
		} else {
			end := strings.IndexByte(s, '|')
			if end < 0 {
				end = len(s)
			}
			alternative, s = s[:end], s[end:]
		}
		if s != "" {
			rest, ok := strings.CutPrefix(s, "|")
			if !ok || rest == "" {
				return nil, fmt.Errorf("want | between field types, not %q", s)
			}
			s = rest
		}

		t, err := parseFieldType(alternative)
		if err != nil {
			return nil, err
		}
		result = append(result, t)
	}
	if len(result) == 0 {
		return nil, fmt.Errorf("no field types")
	}
	return result, nil
}

func parseFieldType(s string) (fieldType, error) {
	switch s {
	case "string", "boolean", "null":
		return fieldType{kind: s}, nil
	}
	if inner, ok := strings.CutPrefix(s, "["); ok {
		inner = strings.TrimSuffix(inner, "]")
		var list []string
		if inner != "" {
			list = strings.Split(inner, "|")
		}
		for _, name := range list {
			if !isNodeTypeName(name) {
				return fieldType{}, fmt.Errorf("%q in %q is not a node type", name, s)
			}
		}
		return fieldType{kind: "list", list: list}, nil
	}
	if !isNodeTypeName(s) {
		return fieldType{}, fmt.Errorf("%q is not a field type", s)
	}
	return fieldType{kind: "node", node: s}, nil
}

// isNodeTypeName reports whether s is an upper case identifier, which
// keeps node types apart from the string, boolean and null kinds.
func isNodeTypeName(s string) bool {
	return token.IsIdentifier(s) && s[0] >= 'A' && s[0] <= 'Z'
}

// setKind checks the field types against the Go type of the field.
func (f *field) setKind(goType string, names map[string]string) error {
	hooks := f.json != "" || f.read != ""
	if hooks && (f.json == "" || f.read == "" || goType != "string") {
		return fmt.Errorf("json and read go together on a string field")
	}

	var want func(fieldType) bool
	switch {
	case goType == "string":
		f.kind = stringKind
		want = func(t fieldType) bool { return t.kind == "string" }
		if hooks {
			want = func(t fieldType) bool { return t.kind == "string" || t.kind == "boolean" }
		}
	case goType == "Node":
		f.kind = nodeKind
		want = func(t fieldType) bool { return t.kind == "node" }
	case goType == "*List[Node]":
		f.kind = listKind
		want = func(t fieldType) bool { return t.kind == "list" }
	case strings.HasPrefix(goType, "*") && names[goType[1:]] != "":
		f.kind = typedNodeKind
		f.goType = goType[1:]
		name := names[f.goType]
		want = func(t fieldType) bool { return t.kind == "node" && t.node == name }
	default:
		return fmt.Errorf("type %q is not string, Node, *List[Node] or a pointer to a node type", goType)
	}

	matching := 0
	for _, t := range f.types {
		switch {
		case want(t):
			matching++
		case t.kind != "null":
			return fmt.Errorf("field type %s does not fit Go type %s", t, goType)
		}
	}
	single := f.kind != nodeKind && !hooks
	if matching == 0 || single && matching > 1 {
		return fmt.Errorf("field types %v do not fit Go type %s", f.types, goType)
	}
	return nil
}

func (t fieldType) String() string {
	switch t.kind {
	case "node":
		return t.node
	case "list":
		return "[" + strings.Join(t.list, "|") + "]"
	default:
		return t.kind
	}
}

// writeConfig writes the NodeConfig of t as an element of a map literal.
func writeConfig(buf *bytes.Buffer, t nodeType) {
	p := func(format string, args ...any) { fmt.Fprintf(buf, format, args...) }

	p("%q: {\n", t.name)
	p("Name: %q,\n", t.name)
	if t.walkContext != "" {
		p("WalkContext: %q,\n", t.walkContext)
	}
	if len(t.fields) == 0 {
		p("Structure: []StructureField{},\n")
	} else {
		p("Structure: []StructureField{\n")
		for _, f := range t.fields {
			var types []string
			for _, ft := range f.types {
				types = append(types, ft.goExpr())
			}
			p("{Name: %q, Types: []FieldType{%s}},\n", f.name, strings.Join(types, ", "))
		}
		p("},\n")
	}
	p("Generate: generate%s,\n", t.goName)
	if slices.ContainsFunc(t.fields, field.walked) {
		p("Walk: walk%s,\n", t.goName)
	}
	p("Clone: clone%s,\n", t.goName)
	p("FromPlainObject: fromPlainObject%s,\n", t.goName)
	p("},\n")
}

func writeNodeType(buf *bytes.Buffer, t nodeType) {
	p := func(format string, args ...any) { fmt.Fprintf(buf, format, args...) }

	p("\n// Type returns %q.\n", t.name)
	p("func (n *%s) Type() string { return %q }\n", t.goName, t.name)
	p("\n// Location returns n.Loc, which is nil when positions are off.\n")
	p("func (n *%s) Location() *Location { return n.Loc }\n", t.goName)

	// MarshalJSON
	p("\n// MarshalJSON encodes n as a JSON object with \"type\", \"loc\" and\n")
	p("// the fields of the node type in structure order.\n")
	p("func (n *%s) MarshalJSON() ([]byte, error) {\n", t.goName)
	if len(t.fields) == 0 {
		p("return marshalNode(n)\n}\n")
	} else {
		p("return marshalNode(n,\n")
		for _, f := range t.fields {
			value := "n." + f.goName
			switch {
			case f.json != "":
				value = f.json + "(" + value + ")"
			case f.kind == stringKind && f.nullable():
				value = "nullableString(" + value + ")"
			}
			p("jsonField{%q, %s},\n", f.name, value)
		}
		p(")\n}\n")
	}

	walked := slices.ContainsFunc(t.fields, field.walked)

	// Walk
	if walked {
		writeWalk(buf, t)
	}

	// Clone
	cloneParam := "_"
	if walked {
		cloneParam = "clone"
	}
	p("\nfunc clone%s(node Node, %s func(Node) Node) Node {\n", t.goName, cloneParam)
	p("c := *node.(*%s)\n", t.goName)
	p("c.Loc = cloneLocation(c.Loc)\n")
	for _, f := range t.fields {
		switch f.kind {
		case nodeKind:
			p("c.%[1]s = clone(c.%[1]s)\n", f.goName)
		case typedNodeKind:
			p("if c.%[1]s != nil {\nc.%[1]s = cloneAs(c.%[1]s, clone)\n}\n", f.goName)
		case listKind:
			p("c.%[1]s = cloneList(c.%[1]s, clone)\n", f.goName)
		}
	}
	p("return &c\n}\n")

	// FromPlainObject
	p("\nfunc fromPlainObject%s(r *PlainObjectReader, object map[string]any) Node {\n", t.goName)
	p("return &%s{\n", t.goName)
	p("Loc: r.Location(object),\n")
	for _, f := range t.fields {
		var read string
		switch {
		case f.read != "":
			read = fmt.Sprintf("%s(r, object, %q)", f.read, f.name)
		case f.kind == stringKind:
			read = fmt.Sprintf("r.String(object, %q)", f.name)
		case f.kind == nodeKind:
			read = fmt.Sprintf("r.Node(object, %q)", f.name)
		case f.kind == typedNodeKind:
			read = fmt.Sprintf("PlainObjectNode[*%s](r, object, %q)", f.goType, f.name)
		case f.kind == listKind:
			read = fmt.Sprintf("r.List(object, %q)", f.name)
		}
		p("%s: %s,\n", f.goName, read)
	}
	p("}\n}\n")
}

// writeWalk writes the WalkFieldsFunc of t, which has a node or list
// field.
func writeWalk(buf *bytes.Buffer, t nodeType) {
	var walks []string
	nodeParam, listParam := "_", "_"
	for _, f := range t.fields {
		switch f.kind {
		case nodeKind, typedNodeKind:
			nodeParam = "walkNode"
			walks = append(walks, fmt.Sprintf("n.%[1]s != nil && walkNode(n.%[1]s)", f.goName))
		case listKind:
			listParam = "walkList"
			walks = append(walks, fmt.Sprintf("n.%[1]s != nil && walkList(n.%[1]s)", f.goName))
		}
	}
	reverseParam := "_"
	if len(walks) > 1 {
		reverseParam = "reverse"
	}

	fmt.Fprintf(buf, "\nfunc walk%s(node Node, %s bool, %s func(Node) bool, %s func(*List[Node]) bool) bool {\n", t.goName, reverseParam, nodeParam, listParam)
	fmt.Fprintf(buf, "n := node.(*%s)\n", t.goName)
	if len(walks) > 1 {
		reversed := slices.Clone(walks)
		slices.Reverse(reversed)
		fmt.Fprintf(buf, "if reverse {\nreturn %s\n}\n", strings.Join(reversed, " ||\n"))
	}
	fmt.Fprintf(buf, "return %s\n}\n", strings.Join(walks, " ||\n"))
}

// goExpr returns the FieldType expression of t in package csstree.
func (t fieldType) goExpr() string {
	switch t.kind {
	case "string":
		return "stringField()"
	case "boolean":
		return "booleanField()"
	case "null":
		return "nullField()"
	case "node":
		return fmt.Sprintf("nodeField(%q)", t.node)
	default:
		quoted := make([]string, len(t.list))
		for i, name := range t.list {
			quoted[i] = strconv.Quote(name)
		}
		return "listField(" + strings.Join(quoted, ", ") + ")"
	}
}
