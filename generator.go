package csstree

import (
	"strings"

	"github.com/typelate/csstree/tokenizer"
)

// GenerateOptions configures Generate. The zero value generates in
// ModeSafe.
type GenerateOptions struct {
	// Mode selects how whitespace between tokens is decided; "" means
	// ModeSafe. Other values are ignored.
	Mode GenerateMode
}

// GenerateMode selects where the generator puts whitespace between
// tokens.
type GenerateMode string

const (
	// ModeSafe adds whitespace between tokens that would otherwise
	// tokenize differently, and also where some browsers need it.
	ModeSafe GenerateMode = "safe"
	// ModeSpec adds whitespace only where CSS Syntax requires it for the
	// CSS to round-trip.
	ModeSpec GenerateMode = "spec"
)

// UnknownNodeTypeError is returned by Generate for a node whose type has no
// generate function. The lexer's Match methods return it for a value they
// cannot generate and for a definition syntax node they cannot match.
type UnknownNodeTypeError struct {
	// Type is the node type: "undefined" for a nil node (as upstream's
	// message reads), and "" for a nil definition syntax node.
	Type string
}

// Error returns "Unknown node type: " and the type, upstream's message.
func (e *UnknownNodeTypeError) Error() string {
	return "Unknown node type: " + e.Type
}

// Generator is what a GenerateFunc writes a node's CSS to. The generator
// adds whitespace between tokens where GenerateOptions.Mode needs it.
type Generator struct {
	h *generateHandlers
}

// Node generates node.
func (g *Generator) Node(node Node) {
	g.h.node(node)
}

// Children generates the nodes of children, calling delimiter (when not
// nil) with the previous node between two nodes.
func (g *Generator) Children(children *List[Node], delimiter func(prev Node)) {
	var prev Node

	for node := range children.All() {
		if delimiter != nil && prev != nil {
			delimiter(prev)
		}

		g.Node(node)
		prev = node
	}
}

// nodeOrNil returns node as a Node, nil for a nil pointer, so that
// generating a missing node field of a pointer type fails with an
// *UnknownNodeTypeError as a missing Node field does (upstream: reading
// the type of null throws).
func nodeOrNil[P interface {
	*T
	Node
}, T any](node P) Node {
	if node == nil {
		return nil
	}
	return node
}

// Token emits a token of tokenType with text value.
func (g *Generator) Token(tokenType tokenizer.TokenType, value string) {
	g.h.token(tokenType, value, false)
}

// Tokenize splits raw into tokens and emits them.
func (g *Generator) Tokenize(raw string) {
	tokenizer.Tokenize(raw, func(tokenType tokenizer.TokenType, start, end int) {
		g.h.token(
			tokenType,
			raw[start:end],
			start != 0, // suppress auto whitespace for internal value tokens
		)
	})
}

// endsWithOpenEscape reports whether str ends with a \ that no \ before it
// escapes.
func endsWithOpenEscape(str string) bool {
	backslashes := 0
	for backslashes < len(str) && str[len(str)-1-backslashes] == reverseSolidus {
		backslashes++
	}
	return backslashes%2 == 1
}

// generateFailure carries an error of the generation (an
// UnknownNodeTypeError, or a bad source mapping) up to the generate
// function.
type generateFailure struct {
	err error
}

// generateHandlers are the output steps of one generation (upstream
// handlers). A decorator replaces some of them with functions calling the
// ones they replace. The default steps call each other through the
// handlers, so they reach the decorated ones (upstream calls them on this).
type generateHandlers struct {
	// node generates node, or fails for an unknown node type.
	node func(node Node)
	// tokenBefore decides on whitespace before a token (see GenerateMode).
	tokenBefore tokenBeforeFunc
	// token emits a token, preceded by whitespace when tokenBefore asks
	// for it unless suppressAutoWhiteSpace is set.
	token func(tokenType tokenizer.TokenType, value string, suppressAutoWhiteSpace bool)
	// emit appends value to the output; autoGenerated marks whitespace the
	// generator added.
	emit func(tokenType tokenizer.TokenType, value string, autoGenerated bool)
	// result returns the output.
	result func() string
}

// generateDecorator changes the handlers of a generation (upstream
// options.decorator, and the source map decorator).
type generateDecorator func(h *generateHandlers)

// generateFunc generates node in mode; decorate, when not nil, changes the
// handlers first.
type generateFunc func(node Node, mode GenerateMode, decorate generateDecorator) (string, error)

// createGenerator returns a generate function for the node types of
// config (upstream createGenerator).
func createGenerator(config *Config) generateFunc {
	types := make(map[string]GenerateFunc)

	if config != nil {
		for name, item := range config.Node {
			if item.Generate != nil {
				types[name] = item.Generate
			}
		}
	}

	return func(node Node, mode GenerateMode, decorate generateDecorator) (result string, err error) {
		var buffer strings.Builder
		prevCode := 0
		// a \ delim was emitted: \ and a newline is not an escape, so a
		// newline goes before the next text unless that text starts with one
		newlineDue := false
		h := new(generateHandlers)
		publicAPI := &Generator{h: h}
		*h = generateHandlers{
			node: func(node Node) {
				if node == nil {
					// upstream: node.type is undefined
					panic(generateFailure{&UnknownNodeTypeError{Type: "undefined"}})
				}
				fn, ok := types[node.Type()]
				if !ok {
					panic(generateFailure{&UnknownNodeTypeError{Type: node.Type()}})
				}
				fn(publicAPI, node)
			},
			tokenBefore: safeTokenBefore(),
			token: func(tokenType tokenizer.TokenType, value string, suppressAutoWhiteSpace bool) {
				prevCode = h.tokenBefore(prevCode, tokenType, value)
				space := !suppressAutoWhiteSpace && prevCode&1 != 0

				if newlineDue && (space || value != "") {
					newlineDue = false
					if space || !startsWithNewline(value) {
						h.emit(tokenizer.WhiteSpace, "\n", true)
					}
				}

				if space {
					h.emit(tokenizer.WhiteSpace, " ", true)
				}

				h.emit(tokenType, value, false)

				// A lone \ must not escape the next char, and a string left open
				// (a bad-string, or a Raw value ending inside a string) must end at
				// a newline (CSS Syntax 4.3.5) instead of swallowing what follows.
				if tokenType == tokenizer.BadString ||
					tokenType == tokenizer.String && !isClosedString(value) ||
					tokenType == tokenizer.Delim && tokenizer.CharCodeAt(value, 0) == reverseSolidus {
					newlineDue = true
				}
			},
			emit: func(_ tokenizer.TokenType, value string, _ bool) {
				buffer.WriteString(value)
			},
			result: buffer.String,
		}

		if decorate != nil {
			decorate(h)
		}

		switch mode {
		case ModeSafe:
			h.tokenBefore = safeTokenBefore()
		case ModeSpec:
			h.tokenBefore = specTokenBefore()
		}

		defer func() {
			if r := recover(); r != nil {
				if failure, ok := r.(generateFailure); ok {
					result, err = "", failure.err
					return
				}
				// a bug in a generate function or an extension
				result, err = "", newInternalError(r)
			}
		}()

		h.node(node)

		if newlineDue {
			h.emit(tokenizer.WhiteSpace, "\n", true)
		}

		return h.result(), nil
	}
}

// Generate turns an AST into CSS text with the default syntax (see
// Syntax.Generate).
func Generate(node Node, options GenerateOptions) (string, error) {
	return defaultParseSyntax().Generate(node, options)
}

// GenerateWithSourceMap is Generate also returning a source map of the
// generated CSS, with the default syntax (see
// Syntax.GenerateWithSourceMap).
func GenerateWithSourceMap(node Node, options GenerateOptions) (string, *SourceMapGenerator, error) {
	return defaultParseSyntax().GenerateWithSourceMap(node, options)
}

// startsWithNewline reports whether text starts with a newline (LF, CR or
// FF; https://drafts.csswg.org/css-syntax-3/#newline).
func startsWithNewline(text string) bool {
	return text != "" && (text[0] == '\n' || text[0] == '\r' || text[0] == '\f')
}

// isClosedString reports whether a string token's text ends with the quote
// it starts with, unescaped. A string token at the end of its input may be
// left open (CSS Syntax 4.3.5: EOF ends the token without a closing quote).
func isClosedString(value string) bool {
	if len(value) < 2 || value[len(value)-1] != value[0] {
		return false
	}

	backslashes := 0
	for i := len(value) - 2; i > 0 && value[i] == '\\'; i-- {
		backslashes++
	}

	return backslashes%2 == 0
}
